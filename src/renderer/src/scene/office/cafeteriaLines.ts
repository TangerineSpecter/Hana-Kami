//
// Two kinds of line:
//   • solo  — one quip above a single agent at a break spot
//   • pair  — a two-beat (or more) exchange between two agents at one table
//
// Lines stay short so they fit the ThoughtBubble (≈MAX_WIDTH, ~12–16 CJK chars
// per line). Character keys match OfficeCharacterName; remapped faces get
// in-character workplace flavour. Anyone without a keyed opener still draws
// from the shared pool, so the floor never goes quiet.

import type { OfficeCharacterName } from './cast';

/** Where an agent is lingering — picks a contextual line pool. */
export type BreakSpot = 'coffee' | 'vending' | 'snack' | 'table';

const pick = <T,>(arr: readonly T[], seed: number): T =>
  arr[((seed % arr.length) + arr.length) % arr.length];

